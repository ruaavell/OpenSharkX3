export function makeT(lang){
  return (key)=>{
    const e = D[key]
    if(!e) return key
    return e[lang] || e.en || e.tr || key
  }
}

export function tAct(s, lang){
  if(!s) return s
  if(lang==='pt') return s
  const e = ACTS[s]
  return e ? (e[lang] || e.en || s) : s
}

export function tModeName(id, lang){
  return makeT(lang)('mode.'+id)
}

export function tModeDesc(id, lang){
  return makeT(lang)('mode.'+id+'.desc')
}
